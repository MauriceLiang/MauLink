const SVG_NS = "http://www.w3.org/2000/svg";

export function iconMarkup(name, className = "icon") {
  const nodes = iconNodes[name];
  if (!nodes) throw new Error(`Unknown Lucide icon: ${name}`);
  const classes = className ? ` class="${className}"` : "";
  const children = nodes.map(([tag, attributes]) => {
    const attrs = Object.entries(attributes).filter(([key]) => key !== "key").map(([key, value]) => ` ${key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}="${String(value)}"`).join("");
    return `<${tag}${attrs}></${tag}>`;
  }).join("");
  return `<svg xmlns="${SVG_NS}" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"${classes}>${children}</svg>`;
}

export function hydrateIcons(root = document) {
  for (const placeholder of root.querySelectorAll("[data-icon]")) {
    const fragment = document.createRange().createContextualFragment(iconMarkup(placeholder.dataset.icon, placeholder.className));
    placeholder.replaceWith(fragment);
  }
}
